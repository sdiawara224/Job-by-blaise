-- Migration additive et idempotente. Aucun statut existant modifié ; pas de notification rétroactive.
-- Le changement de statut et sa notification font partie de la même transaction.
create table if not exists jobbyblaise.notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references jobbyblaise.users(id) on delete cascade,
  application_id bigint references jobbyblaise.applications(id) on delete set null,
  job_title text not null,
  company_name text not null,
  old_status text not null,
  new_status text not null,
  created_at timestamptz not null default now(),
  is_read integer not null default 0 check (is_read in (0, 1))
);
alter table jobbyblaise.notifications enable row level security;
create index if not exists ix_notifications_user_id on jobbyblaise.notifications(user_id, id);

create or replace function jobbyblaise.notify_application_status()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into jobbyblaise.notifications (user_id, application_id, job_title, company_name, old_status, new_status)
  select NEW.user_id, NEW.id, j.title, c.name, OLD.status, NEW.status
  from jobbyblaise.jobs j join jobbyblaise.companies c on c.id = j.company_id
  where j.id = NEW.job_id;
  return NEW;
end;
$$;
revoke all on function jobbyblaise.notify_application_status() from public;
drop trigger if exists application_status_notification on jobbyblaise.applications;
create trigger application_status_notification
  after update of status on jobbyblaise.applications
  for each row when (OLD.status is distinct from NEW.status)
  execute function jobbyblaise.notify_application_status();
