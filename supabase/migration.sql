-- ------------------------------------------------- 3. RPC app_exec
-- Reçoit { p_kind: 'one'|'rows'|'run', p_sql: <SQL avec ?>, p_params: [...] }
-- et renvoie : row | [rows] | { changes, lastInsertRowid }.
-- Les valeurs sont liées côté serveur via quote_literal (jamais concaténées
-- depuis le client) ; l'authentification repose sur la clé de service.
create or replace function public.app_exec(p_kind text, p_sql text, p_params jsonb default '[]'::jsonb)
returns jsonb
language plpgsql
security definer
set search_path = jobbyblaise, public, pg_temp
as $fn$
declare
  n        int := coalesce(jsonb_array_length(p_params), 0);
  parts    text[];
  sql_out  text;
  i        int;
  v_id     bigint;
  v_n      bigint;
  v_result jsonb;
  v_role   text;
begin
  -- Restreint aux rôles de service (la fonction n'est jamais appelée depuis le front)
  v_role := coalesce(auth.role(), current_user);
  if v_role not in ('service_role', 'postgres') then
    raise exception 'accès refusé (rôle : %)', v_role using errcode = '42501';
  end if;

  -- Découpe sur les placeholders ? et injection liée des valeurs
  parts := regexp_split_to_array(p_sql, '\?');
  if coalesce(array_length(parts, 1), 1) - 1 <> n then
    raise exception 'paramètres incohérents : % placeholder(s) pour % valeur(s)',
      coalesce(array_length(parts, 1), 1) - 1, n;
  end if;

  sql_out := parts[1];
  for i in 1 .. n loop
    if p_params->(i - 1) is null or jsonb_typeof(p_params->(i - 1)) = 'null' then
      sql_out := sql_out || 'NULL';
    else
      sql_out := sql_out || quote_literal(p_params->> (i - 1));
    end if;
    sql_out := sql_out || parts[i + 1];
  end loop;

  if p_kind = 'one' then
    execute 'SELECT row_to_json(t)::jsonb FROM (' || sql_out || ') t' into v_result;
    return coalesce(v_result, 'null'::jsonb);

  elsif p_kind = 'rows' then
    -- row_number fige l'ordre d'émission des lignes (équivalent de l'ORDER BY SQLite)
    execute
      'SELECT coalesce(jsonb_agg((row_to_json(t)::jsonb - ''__ord'') ORDER BY t.__ord), ''[]''::jsonb) '
      || 'FROM (SELECT _x.*, row_number() OVER () AS __ord FROM (' || sql_out || ') _x) t'
    into v_result;
    return coalesce(v_result, '[]'::jsonb);

  elsif p_kind = 'run' then
    if sql_out ~* '^\s*insert' then
      begin
        -- lastInsertRowid : renvoyé via RETURNING id (tables sans colonne id → repli)
        execute sql_out || ' RETURNING id' into v_id;
        get diagnostics v_n = row_count;
      exception when undefined_column then
        execute sql_out;
        get diagnostics v_n = row_count;
        v_id := 0;
      end;
      return jsonb_build_object('changes', v_n, 'lastInsertRowid', coalesce(v_id, 0));
    end if;
    execute sql_out;
    get diagnostics v_n = row_count;
    return jsonb_build_object('changes', v_n, 'lastInsertRowid', 0);

  else
    raise exception 'kind inconnu : %', p_kind;
  end if;
end;
$fn$;

-- La fonction reste dans `public` (schéma exposé par PostgREST) ;
-- Privileges : service only (le PUBLIC a EXECUTE par défaut → révocation obligatoire)
revoke execute on function public.app_exec (text, text, jsonb) from public, anon, authenticated;
grant  execute on function public.app_exec (text, text, jsonb) to postgres, service_role;
