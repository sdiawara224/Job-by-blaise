create table if not exists jobbyblaise.jobs (
  id             bigint generated by default as identity primary key,
  company_id     bigint not null references jobbyblaise.companies (id),
  title          text not null,
  city           text not null,
  country        text not null default 'Guinée',
  contract       text not null default 'Temps plein',
  salary_min     integer default 0,
  salary_max     integer default 0,
  experience_min integer default 0,
  education_min  text default '',
  domain         text default 'Administration',
  description    text default '',
  requirements   text default '',
  skills         text default '[]',
  posted_at      timestamptz default now(),
  is_active      integer default 1
);

create table if not exists jobbyblaise.applications (
  id           bigint generated by default as identity primary key,
  user_id      bigint not null references jobbyblaise.users (id),
  job_id       bigint not null references jobbyblaise.jobs (id),
  cover_letter text default '',
  status       text not null default 'En attente',
  created_at   timestamptz default now(),
  unique (user_id, job_id)
);

create table if not exists jobbyblaise.alert_settings (
  user_id       bigint primary key references jobbyblaise.users (id),
  enabled       integer default 1,
  phone         text default '',
  send_time     text default '07:00',
  keywords      text default '[]',
  cities        text default '[]',
  contracts     text default '[]',
  last_sent_on  text default '',
  updated_at    timestamptz default now()
);

create table if not exists jobbyblaise.sms_messages (
  id        bigint generated by default as identity primary key,
  user_id   bigint not null references jobbyblaise.users (id),
  body      text not null,
  sent_at   timestamptz default now(),
  is_read   integer default 0
);

create table if not exists jobbyblaise.advice (
  id       bigint generated by default as identity primary key,
  title    text not null,
  category text not null,
  excerpt  text default '',
  content  text default '',
  minutes  integer default 4,
  color    text default '#2E6BFF'
);

