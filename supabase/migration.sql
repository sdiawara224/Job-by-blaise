create table if not exists jobbyblaise.companies (
  id           bigint generated by default as identity primary key,
  name         text not null,
  sector       text not null,
  city         text not null,
  description  text default '',
  color        text default '#2E6BFF',
  founded_year integer,
  staff_size   text
